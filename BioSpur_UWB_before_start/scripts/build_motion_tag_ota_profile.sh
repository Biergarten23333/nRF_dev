  TAG_ID="${TAG_ID:-$1}"
  TAG_BUILD_DIR="${2:-build-tag-ota-motion-tag${TAG_ID}}"
  MASTER_BUILD_DIR="${3:-build-master-ota-motion-tag${TAG_ID}}"
