      if [[ "$TAG_ID" =~ ^[0-9]+$ ]] && [ "$TAG_ID" -lt 10 ]; then
        TAG_LOGICAL_ID="$TAG_ID"
      else
        TAG_LOGICAL_ID="0"
      fi
      ;;
  esac
fi
